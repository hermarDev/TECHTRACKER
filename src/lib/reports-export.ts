import { unparse } from "papaparse";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

/**
 * reports-export.ts — Domain C report rendering (14W / 09W / 16W)
 *
 * CSV output via papaparse (`unparse`).
 * PDF output via jspdf + jspdf-autotable (`autoTable`).
 * All helpers are pure presentational functions: they accept already-fetched
 * data and return a CSV string or a PDF Buffer. They never touch Prisma so
 * they stay unit-testable without a database.
 */

type CsvRow = Record<string, unknown>;

function sanitizeCsvCell(value: unknown): unknown {
  if (typeof value !== "string") return value;
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
}

// ---------------------------------------------------------------------------
// CSV (papaparse)
// ---------------------------------------------------------------------------

export function generateCsv(rows: readonly CsvRow[]): string {
  if (rows.length === 0) return "";
  const safeRows = rows.map((row) =>
    Object.fromEntries(Object.entries(row).map(([k, v]) => [k, sanitizeCsvCell(v)]))
  );
  return unparse(safeRows);
}

export function generateCsvWithFields<T extends object>(
  fields: readonly string[],
  rows: T[]
): string {
  if (rows.length === 0) return "";
  // Project each row onto the requested field order so column headers match.
  const projected = rows.map((row) => {
    const record = row as CsvRow;
    const out: CsvRow = {};
    for (const field of fields) {
      out[field] = sanitizeCsvCell(record[field]);
    }
    return out;
  });
  return unparse({ fields: [...fields], data: projected });
}

// ---------------------------------------------------------------------------
// PDF (jspdf + jspdf-autotable)
// ---------------------------------------------------------------------------

interface PdfOptions {
  title: string;
  headers: string[];
  rows: (string | number | null | undefined)[][];
}

export function generatePdf(options: PdfOptions): Buffer {
  const { title, headers, rows } = options;
  const doc = new jsPDF();
  doc.setFontSize(16);
  doc.text(title, 14, 16);
  doc.setFontSize(10);
  doc.text("Generated by TechTracker (ACLC College of Mandaue — BSIT Pre-OJT)", 14, 24);

  const body = rows.map((row) =>
    row.map((cell) => (cell === null || cell === undefined ? "" : String(cell)))
  );

  // jspdf-autotable v5 exposes a functional API: autoTable(doc, options).
  autoTable(doc, {
    head: [headers],
    body,
    startY: 34,
    styles: { fontSize: 9, cellPadding: 3 },
    headStyles: { fillColor: [41, 128, 185], textColor: [255, 255, 255] },
  });

  const output = doc.output("arraybuffer");
  return Buffer.from(output);
}

// ---------------------------------------------------------------------------
// Domain-specific report builders
// ---------------------------------------------------------------------------

export interface InspectionSummaryRow {
  room: string;
  unitCode: string;
  condition: string;
  remarks: string;
  photoKey: string | null;
  inspectedAt: string;
  inspector: string;
}

export function generateInspectionSummaryCsv(rows: InspectionSummaryRow[]): string {
  const fields: (keyof InspectionSummaryRow)[] = [
    "room",
    "unitCode",
    "condition",
    "remarks",
    "photoKey",
    "inspectedAt",
    "inspector",
  ];
  return generateCsvWithFields(fields, rows);
}

export function generateInspectionSummaryPdf(rows: InspectionSummaryRow[]): Buffer {
  const headers = [
    "Room",
    "Unit Code",
    "Condition",
    "Defect Remarks",
    "Photo Key",
    "Inspected At",
    "Inspector",
  ];
  const body = rows.map((r) => [
    r.room,
    r.unitCode,
    r.condition,
    r.remarks ?? "",
    r.photoKey ?? "",
    r.inspectedAt,
    r.inspector,
  ]);
  return generatePdf({
    title: "Lab Condition Summary Report — Room/Unit Inspection",
    headers,
    rows: body,
  });
}

export interface OperationalReportRow {
  batch: string;
  section: string;
  metric: string;
  value: string;
  label: string;
}

export function generateOperationalReportCsv(rows: OperationalReportRow[]): string {
  const fields: (keyof OperationalReportRow)[] = ["batch", "section", "metric", "value", "label"];
  return generateCsvWithFields(fields, rows);
}

export function generateOperationalReportPdf(rows: OperationalReportRow[]): Buffer {
  const headers = ["Batch", "Section", "Metric", "Value", "Label"];
  const body = rows.map((r) => [r.batch, r.section, r.metric, r.value, r.label]);
  return generatePdf({
    title: "Operational Report — Attendance, Duty Hours, Task Progress, Lab Equipment",
    headers,
    rows: body,
  });
}
