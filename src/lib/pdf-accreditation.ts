import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

export interface AccreditationStudent {
  fullName: string;
  studentIdNo: string | null;
  program: string | null;
  section: string | null;
  requiredHours: number;
}

export interface AccreditationAttendance {
  shiftDate: Date;
  timeIn: Date;
  timeOut: Date | null;
  creditedHours: number;
  isIrregular: boolean;
}

export function generateAccreditationPdf(
  student: AccreditationStudent,
  logs: AccreditationAttendance[]
): Uint8Array {
  const doc = new jsPDF();
  doc.setFontSize(14);
  doc.text("100-Hour Internal Duty Accreditation Summary Log", 14, 18);
  doc.setFontSize(9);
  doc.text("TechTracker - ACLC College of Mandaue", 14, 25);
  doc.text(`Student: ${student.fullName}`, 14, 34);
  doc.text(`Student ID: ${student.studentIdNo ?? "—"}`, 14, 40);
  doc.text(`Program / Section: ${student.program ?? "—"} / ${student.section ?? "—"}`, 14, 46);
  doc.text(`Required hours: ${student.requiredHours.toFixed(2)}`, 14, 52);

  autoTable(doc, {
    startY: 60,
    head: [["Date", "Time-In", "Time-Out", "Credited Hours", "Status"]],
    body: logs.map((log) => [
      log.shiftDate.toLocaleDateString(),
      log.timeIn.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      log.timeOut?.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }) ?? "—",
      log.creditedHours.toFixed(2),
      log.isIrregular ? "Irregular" : "Approved",
    ]),
    styles: { fontSize: 8 },
  });

  const total = logs.reduce((sum, log) => sum + log.creditedHours, 0);
  const finalY = (doc as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 65;
  doc.setFontSize(10);
  doc.text(`Total credited hours: ${total.toFixed(2)}`, 14, finalY + 12);
  doc.text("Generated by TechTracker", 14, finalY + 22);
  return new Uint8Array(doc.output("arraybuffer"));
}
